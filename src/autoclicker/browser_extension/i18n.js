export function translator(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return (key, params = {}) =>
    (dict[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}

export function defaultLanguage() {
  return (chrome.i18n.getUILanguage() || "en").toLowerCase().startsWith("vi") ? "vi" : "en";
}
